// Cari dil (yaddasda saxlanilir ki, sehifeler arasi qalsin)
function getLang() {
  return localStorage.getItem("lang") || "az";
}

function setLang(lang) {
  const changed = localStorage.getItem("lang") !== lang;
  localStorage.setItem("lang", lang);
  applyTranslations();
  updateLangButtons();
  // Dil deyisdise sehifeni yenile ki, JS ile yaranan metnler (kartlar,
  // emeliyyatlar, select) de yeni dilde render olunsun.
  if (changed) location.reload();
}

// Butun data-i18n elementlerini tercume et
function applyTranslations() {
  const lang = getLang();
  const dict = I18N[lang] || I18N.az;

  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    if (dict[key] !== undefined) el.textContent = dict[key];
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
    const key = el.getAttribute("data-i18n-placeholder");
    if (dict[key] !== undefined) el.setAttribute("placeholder", dict[key]);
  });

  document.querySelectorAll("[data-i18n-title]").forEach(el => {
    const key = el.getAttribute("data-i18n-title");
    if (dict[key] !== undefined) el.setAttribute("title", dict[key]);
  });

  document.documentElement.lang = lang;
}

// Dil duymelerinin aktiv gorunusu
function updateLangButtons() {
  const lang = getLang();
  document.querySelectorAll("[data-lang]").forEach(btn => {
    const on = btn.dataset.lang === lang;
    if (btn.classList.contains("lang-opt")) {
      // dropdown daxili secim
      btn.className = "lang-opt flex items-center justify-between w-full px-3 py-2 rounded-lg text-xs font-500 transition " +
        (on ? "bg-neon/12 text-teal-700" : "text-ink/60 hover:bg-mist");
    } else {
      btn.className = "lang-btn px-3 py-1.5 rounded-lg text-xs font-500 transition " +
        (on ? "bg-ink text-white" : "text-ink/40 hover:text-ink");
    }
  });
  // dropdown trigger etiketi
  const ll = document.getElementById("langTriggerLabel");
  if (ll) ll.textContent = lang.toUpperCase();
}

// Tercume acari ile metn al (JS-den istifade ucun)
function t(key) {
  const dict = I18N[getLang()] || I18N.az;
  return dict[key] !== undefined ? dict[key] : key;
}

// Sehife yuklenende avtomatik tetbiq et
document.addEventListener("DOMContentLoaded", () => {
  applyTranslations();
  updateLangButtons();
  document.querySelectorAll("[data-lang]").forEach(btn => {
    btn.addEventListener("click", () => setLang(btn.dataset.lang));
  });
});